const PARTICLE_SUFFIXES = [
  "에서는", "에서도", "입니다", "습니다", "네요", "세요", "해요", "예요",
  "이에요", "에서", "에게", "한테", "께서", "으로", "이랑", "까지", "부터",
  "처럼", "보다", "마다", "조차", "마저", "은", "는", "이", "가", "을", "를",
  "도", "만", "에", "의", "와", "과", "로", "랑",
];

function stripParticle(token) {
  for (const suffix of PARTICLE_SUFFIXES) {
    const stem = token.length - suffix.length;
    // 단일 조사(은/는/이/가…)는 3글자 고유명사(김고은→김고)를 훼손하므로 더 보수적으로:
    // 남는 stem이 3글자 이상일 때만 제거. 2글자 이상 어미는 기존대로.
    const minStem = suffix.length === 1 ? 3 : 2;
    if (token.endsWith(suffix) && stem >= minStem) {
      return token.slice(0, stem);
    }
  }
  return token;
}

export function tokenize(text) {
  return text
    .replace(/https?:\/\/\S+/g, " ")
    .replace(/[\u{1F000}-\u{1FFFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, " ")
    .replace(/[ㅋㅎㅠㅜ]{2,}/g, " ")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .split(/\s+/)
    .map((token) => stripParticle(token.trim()))
    .filter(
      (token) =>
        token.length >= 2 &&
        token.length <= 20 &&
        !/^\d+$/.test(token) &&
        !/^[ㄱ-ㅣ]+$/.test(token) &&
        !/갤$/.test(token) && // 디시 [XX갤] 출처 태그(싱갤·호갤…) 제거
        // 영어 불용어는 소문자로 등재돼 있는데 원문엔 "The"·"Official"처럼 대문자로
        // 나온다. 소문자로 낮춰 비교해야 실제로 걸린다.
        !STOPWORDS.has(token.toLowerCase())
    );
}
